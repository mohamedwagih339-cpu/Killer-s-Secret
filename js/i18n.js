let currentLang = localStorage.getItem("detective_lang") || "ar";

function t(key) {
  const langObj = translations[currentLang];
  return langObj && langObj[key] ? langObj[key] : key;
}

function tf(key, params) {
  let text = t(key);
  if (params) {
    Object.keys(params).forEach((name) => {
      text = text.split("{" + name + "}").join(String(params[name]));
    });
  }
  return text;
}

function setLanguage(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem("detective_lang", lang);
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = lang;
    updateAllTexts();
    if (typeof refreshConfirmDialogText === "function") refreshConfirmDialogText();

    if (typeof gameState !== "undefined" && gameState.currentCase) {
      if (gameState.currentScreen === "interrogation" && gameState.activeSuspectId && typeof renderInterrogation === "function") {
        renderInterrogation(gameState.activeSuspectId);
      } else if (gameState.currentScreen === "suspects" && typeof renderSuspects === "function") {
        renderSuspects();
      } else if (gameState.currentScreen === "intro" && typeof renderIntro === "function") {
        renderIntro();
      } else if (gameState.currentScreen === "accusation" && typeof renderAccusation === "function") {
        renderAccusation();
      } else if (gameState.currentScreen === "caseEnd" && typeof renderCaseEnd === "function") {
        const latest = typeof getLatestCaseResult === "function"
          ? getLatestCaseResult(gameState.currentCase.id)
          : null;
        if (latest) renderCaseEnd(latest);
      }
      if (typeof renderTabletEvidence === "function") {
        renderTabletEvidence();
        renderTabletSuspects();
      }
      if (typeof renderTabletLab === "function") {
        renderTabletLab();
      }
    }

    if (typeof gameState !== "undefined") {
      if (typeof renderHomeRankCard === "function") renderHomeRankCard();
      if (typeof renderTabletRankCard === "function") renderTabletRankCard();
      if (gameState.currentScreen === "playerName" && typeof renderNameScreen === "function") {
        renderNameScreen();
      }
      if (gameState.currentScreen === "characterDesign" && typeof renderDesigner === "function") {
        renderDesigner();
      }
      if (gameState.currentScreen === "promotion" && typeof renderPromotion === "function") {
        renderPromotion();
      }
    }
    const skillsScreen = document.getElementById("tablet-skills");
    if (skillsScreen && !skillsScreen.classList.contains("hidden") && typeof renderSkillsApp === "function") {
      renderSkillsApp();
    }
  }
}

function updateAllTexts() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
  });
}